def main():
    c=psycopg2.connect(os.environ["DATABASE_URL"]);cur=c.cursor()
    cur.execute("select current_database()")
    if cur.fetchone()[0]!="lingce_dev": raise SystemExit("not dev")
    # patient operation tasks
    cur.execute("select t.id,c.name from patient_operation_tasks t join customers c on c.id=t.customer_id where t.tenant_id=1")
    for tid,name in cur.fetchall():
        t=TASKS.get(name)
        if not t: continue
        title,action,msg,reason=t
        cur.execute("update patient_operation_tasks set goal=%s,action=%s,content=%s,evidence=%s where id=%s",(title,action,msg,reason,tid))
    # followup tasks
    cur.execute("select id,customer_name from recording_tasks where tenant_id=1")
    for tid,name in cur.fetchall():
        t=FOLLOW.get(name)
        if not t: continue
        title,desc,script,reason=t
        cur.execute("update recording_tasks set title=%s,description=%s,script=%s,contact_reason=%s,assigned_to=213 where id=%s",(title,desc,script,reason,tid))
    # compliance items
    cur.execute("select id,theme_key from compliance_check_items where tenant_id=1")
    for cid,theme in cur.fetchall():
        t=COMP.get(theme)
        if not t: continue
        q,hyp,basis,actions=t
        cur.execute("update compliance_check_items set question=%s,risk_hypothesis=%s,check_basis=%s,suggested_actions=%s where id=%s",(q,hyp,Json(basis),Json(actions),cid))
    c.commit();print('humanized other products');cur.close();c.close()

