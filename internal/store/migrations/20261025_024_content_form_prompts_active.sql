A. 被理解（治愈型）——读者觉得「终于有人懂我」。例：「你不是想多了，你的身体真的在提醒你。」
B. 被点醒（认知型）——读者觉得「原来如此，我该重视」。例：「结节不是等它长大，是趁它还小的时候搞明白它到底是什么。」
C. 被代言（想跟谁说却说不出）——读者觉得「这就是我想跟爸妈说的话」。例：「怕冷不是矫情，是身体在提醒你该看看了。」
约束：一句话、不超过 30 字、是读者的共鸣、不是医院广告、绝不出现「转发/分享/点赞」字样。

